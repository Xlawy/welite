describe('WeLite login across file manager and reader', function()
    local Storage, Settings, LuaSettings, root, full, settings_dir
    setup(function()
        require('commonrequire')
        package.path='plugins/weread.koplugin/?.lua;'..package.path
        Storage=require('datastorage')
        Settings=require('weread.lib.settings')
        LuaSettings=require('luasettings')
    end)
    before_each(function()
        root=os.tmpname();os.remove(root)
        require('libs/libkoreader-lfs').mkdir(root)
        require('libs/libkoreader-lfs').mkdir(root..'/settings')
        full,settings_dir=Storage.getFullDataDir,Storage.getSettingsDir
        Storage.getFullDataDir=function() return root end
        Storage.getSettingsDir=function() return root..'/settings' end
    end)
    after_each(function()
        Storage.getFullDataDir,Storage.getSettingsDir=full,settings_dir
        require('ffi/util').purgeDir(root)
    end)
    it('shares committed login and logout without a stale instance overwriting credentials', function()
        local manager=Settings:new()
        local reader=Settings:new()
        assert.is_false(manager:is_api_configured())
        reader:update_auth({api_key='fixture-key',cookies={wr_vid='123',wr_skey='fixture-session'},
            account={login_method='qr',user_vid='123'}}, {replace_cookies=true})
        assert.is_true(manager:is_api_configured())
        assert.is_true(manager:is_cookie_configured())
        local Common=require('weread.ui.common')
        assert.is_true(Common.requireLogin({settings=manager},true,true))
        manager:set('fixture_preference',true);manager:flush()
        local disk=LuaSettings:open(manager.settings_file)
        assert.equals('fixture-key',disk:readSetting('api_key'))
        manager:reset_account()
        assert.is_false(reader:is_api_configured())
        assert.is_false(reader:is_cookie_configured())
        reader:flush()
        assert.equals('',LuaSettings:open(manager.settings_file):readSetting('api_key'))
    end)
    it('keeps separate profile stores isolated',function()
        local first=Settings:new()
        Storage.getSettingsDir=function() return root..'/other-settings' end
        require('libs/libkoreader-lfs').mkdir(root..'/other-settings')
        local other=Settings:new()
        first:update_auth({api_key='first-profile'})
        assert.is_false(other:is_api_configured())
        assert.are_not.equal(first.store,other.store)
    end)
end)
