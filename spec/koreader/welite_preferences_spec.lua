describe('welite display and startup preferences',function()
    local P,settings,path
    setup(function() require('commonrequire');package.path='plugins/weread.koplugin/?.lua;'..package.path;P=require('weread.ui.welite.preferences') end)
    before_each(function() path=os.tmpname();os.remove(path);settings=require('luasettings'):open(path) end)
    after_each(function() os.remove(path);os.remove(path..'.old') end)
    it('validates quarter-hour offsets and formats UTC rollover independently of the device clock',function()
        assert.equals(480,P.parse('+08:00'));assert.equals(-210,P.parse('-03:30'));assert.equals(345,P.parse('+05:45'))
        assert.equals(840,P.parse('+14:00'));assert.equals(-720,P.parse('-12:00'))
        for _,s in ipairs({'08:00','+14:15','-12:15','+05:60','+05:17','bad'}) do assert.is_nil(P.parse(s)) end
        P.save({timezone=true,offset=345},settings)
        assert.equals('1970-01-01 05:45',P.date('%Y-%m-%d %H:%M',0,settings))
        P.save({timezone=true,offset=-210},settings)
        assert.equals('1969-12-31 20:30',P.date('%Y-%m-%d %H:%M',0,settings))
        P.save({timezone=true},settings);assert.equals(os.date('%H:%M',0),P.date('%H:%M',0,settings))
    end)
    it('persists choices independently and falls back safely for malformed settings',function()
        assert.is_false(P.read(settings).decided)
        P.save({timezone=true,offset=480},settings);assert.is_false(P.read(settings).decided)
        P.save({autostart=false},settings)
        settings=require('luasettings'):open(path)
        assert.is_true(P.read(settings).decided);assert.is_false(P.read(settings).autostart);assert.equals(480,P.read(settings).offset)
        P.save({autostart=true},settings);assert.is_true(P.read(settings).autostart)
        settings:saveSetting('welite_preferences',{offset=9999,autostart='yes'})
        assert.is_nil(P.read(settings).offset);assert.is_false(P.read(settings).decided)
    end)
    it('persists shelf choices separately and validates damaged preferences',function()
        P.save({autostart=true,timezone=true,offset=480},settings)
        P.saveShelf({category='local',sort='recent',download_filter='partial'},settings)
        local reopened=require('luasettings'):open(path)
        assert.same({category='local',sort='recent',download_filter='partial'},P.readShelf(reopened))
        assert.equals(480,P.read(reopened).offset);assert.is_true(P.read(reopened).autostart)
        settings:saveSetting('welite_shelf_preferences',{category='bad',sort='bad',download_filter='bad'})
        assert.same({category='shelf',sort='cloud',download_filter='all'},P.readShelf(settings))
        settings:saveSetting('welite_shelf_preferences',{category='local',download_filter='none'})
        assert.equals('all',P.readShelf(settings).download_filter)
        local writes=0
        local memory={readSetting=function() return {category='shelf',sort='cloud',download_filter='all'} end,
            saveSetting=function() writes=writes+1 end,flush=function() writes=writes+1 end}
        P.saveShelf({category='shelf',sort='cloud',download_filter='all'},memory)
        assert.equals(0,writes)
    end)

end)
